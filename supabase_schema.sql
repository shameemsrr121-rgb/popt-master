        SELECT 1 FROM pg_policies WHERE policyname = 'Public Read po-attachments'
    ) THEN
        CREATE POLICY "Public Read po-attachments" ON storage.objects
        FOR SELECT USING (bucket_id = 'po-attachments');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE policyname = 'Public Upload po-attachments'
    ) THEN
        CREATE POLICY "Public Upload po-attachments" ON storage.objects
        FOR INSERT WITH CHECK (bucket_id = 'po-attachments');
    END IF;
END $$;

