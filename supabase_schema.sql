-- Enable extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. USERS & ACCESS RIGHTS
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    full_name TEXT DEFAULT '',
    role TEXT DEFAULT 'User', -- 'Administrator', 'Procurement Lead', 'Store Keeper', etc.
    is_admin BOOLEAN DEFAULT false,
    can_delete_po BOOLEAN DEFAULT true,
    show_procurement BOOLEAN DEFAULT true,
    show_inventory BOOLEAN DEFAULT true,
    show_supplier BOOLEAN DEFAULT true,
    show_report BOOLEAN DEFAULT true,
    show_margin BOOLEAN DEFAULT true,
    show_google_sheets BOOLEAN DEFAULT true,
    show_admin_panel BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. COMPANY PROFILE
CREATE TABLE IF NOT EXISTS public.company_profile (
    id BIGINT PRIMARY KEY DEFAULT 1,
    company_name TEXT NOT NULL DEFAULT 'PO Master ERP',
    address TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    gst_number TEXT DEFAULT '',
    website TEXT DEFAULT '',
    logo_uri TEXT DEFAULT NULL,
    bank_name TEXT DEFAULT '',
    account_number TEXT DEFAULT '',
    ifsc_code TEXT DEFAULT '',
    terms_and_conditions TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. SUPPLIERS
CREATE TABLE IF NOT EXISTS public.suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    contact_person TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    address TEXT DEFAULT '',
    payment_terms TEXT DEFAULT 'Net 30', -- 'Net 30', 'Net 60', 'COD', 'Advance'
    rating NUMERIC(3, 1) DEFAULT 4.0,
    category TEXT DEFAULT 'Readymade',
    default_margin_percent NUMERIC(5, 2) DEFAULT 30.0,
    gst_number TEXT DEFAULT '',
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. LOCATIONS / BRANCHES / WAREHOUSES
CREATE TABLE IF NOT EXISTS public.locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    address TEXT DEFAULT '',
    type TEXT DEFAULT 'Warehouse', -- 'Warehouse', 'Retail Outlet', 'Distribution Hub'
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. INVENTORY & PRODUCT MASTER
CREATE TABLE IF NOT EXISTS public.inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    category TEXT DEFAULT 'General',
    unit TEXT DEFAULT 'Pcs', -- 'Pcs', 'Kg', 'Liters', 'Boxes', 'Sheets'
    unit_cost NUMERIC(12, 2) DEFAULT 0.0,
    standard_selling_price NUMERIC(12, 2) DEFAULT 0.0,
    current_stock INT DEFAULT 0,
    min_reorder_level INT DEFAULT 10,
    default_supplier_id BIGINT REFERENCES public.suppliers(id) ON DELETE SET NULL,
    -- Hierarchy & Matrix Attributes (for garments/textiles/retail)
    division TEXT DEFAULT 'Readymade',
    section TEXT DEFAULT 'Main Store',
    department TEXT DEFAULT 'General',
    category1 TEXT DEFAULT '', -- Brand / Designer
    category2 TEXT DEFAULT '', -- Season / Collection
    category3 TEXT DEFAULT '', -- Fabric / Material
    category4 TEXT DEFAULT '', -- Fit / Style
    category5 TEXT DEFAULT '', -- Size Matrix
    category6 TEXT DEFAULT '', -- Color / Pattern
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. PURCHASE ORDERS
CREATE TABLE IF NOT EXISTS public.purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number TEXT UNIQUE NOT NULL,
    supplier_id BIGINT REFERENCES public.suppliers(id) ON DELETE SET NULL,
    supplier_name TEXT NOT NULL,
    order_date_millis BIGINT NOT NULL,
    expected_delivery_date_millis BIGINT NOT NULL,
    payment_terms TEXT DEFAULT 'Net 30',
    status TEXT DEFAULT 'DRAFT', -- 'DRAFT', 'ISSUED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED'
    subtotal NUMERIC(14, 2) DEFAULT 0.0,
    tax_amount NUMERIC(14, 2) DEFAULT 0.0,
    total_amount NUMERIC(14, 2) DEFAULT 0.0,
    notes TEXT DEFAULT '',
    photo_uri TEXT DEFAULT NULL, -- Cloud Storage URL of PO receipt/sample
    location TEXT DEFAULT 'Central Warehouse',
    created_by TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. PURCHASE ORDER ITEMS (Line Items)
CREATE TABLE IF NOT EXISTS public.po_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id BIGINT NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
    inventory_item_id BIGINT DEFAULT NULL,
    item_sku TEXT DEFAULT '',
    item_name TEXT NOT NULL,
    quantity_ordered INT NOT NULL,
    quantity_received INT DEFAULT 0,
    unit_price NUMERIC(12, 2) NOT NULL,
    tax_percent NUMERIC(5, 2) DEFAULT 5.0,
    taxable_amount NUMERIC(14, 2) DEFAULT 0.0,
    tax_amount NUMERIC(14, 2) DEFAULT 0.0,
    total_price NUMERIC(14, 2) NOT NULL,
    photo_uri TEXT DEFAULT NULL, -- Cloud Storage URL of sample/item photo
    location TEXT DEFAULT 'Central Warehouse',
    division TEXT DEFAULT '',
    section TEXT DEFAULT '',
    department TEXT DEFAULT '',
    c1_brand TEXT DEFAULT '',
    c2_size TEXT DEFAULT '',
    c3_design TEXT DEFAULT '',
    c4_colour TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. PO TAX BREAKDOWNS (GST Slabs)
CREATE TABLE IF NOT EXISTS public.po_tax_breakdowns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id BIGINT NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
    gst_percent NUMERIC(5, 2) NOT NULL,
    taxable_amount NUMERIC(14, 2) NOT NULL,
    cgst_percent NUMERIC(5, 2) NOT NULL,
    cgst_amount NUMERIC(14, 2) NOT NULL,
    sgst_percent NUMERIC(5, 2) NOT NULL,
    sgst_amount NUMERIC(14, 2) NOT NULL,
    total_tax_amount NUMERIC(14, 2) NOT NULL
);

-- 9. SOURCING TRIP & PURCHASE PLANNING NOTES
CREATE TABLE IF NOT EXISTS public.purchase_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL, -- e.g. "Bombay Trip - Silk Sourcing"
    planned_date_millis BIGINT NOT NULL,
    to_date_millis BIGINT DEFAULT 0,
    location TEXT DEFAULT '', -- e.g. "Bombay", "Surat", "Tirupur"
    notes TEXT DEFAULT '',
    estimated_budget NUMERIC(14, 2) DEFAULT 0.0,
    category_or_supplier TEXT DEFAULT '',
    priority TEXT DEFAULT 'MEDIUM', -- 'HIGH', 'MEDIUM', 'LOW'
    status TEXT DEFAULT 'PLANNED', -- 'PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CONVERTED_TO_PO'
    reminder_days_before INT DEFAULT 1,
    converted_po_id BIGINT REFERENCES public.purchase_orders(id) ON DELETE SET NULL,
    created_by TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. CATEGORY TAX RULES (HSN / GST Rules)
CREATE TABLE IF NOT EXISTS public.category_tax_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL,
    hsn_code TEXT DEFAULT '',
